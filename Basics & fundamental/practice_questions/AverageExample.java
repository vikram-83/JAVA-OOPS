public class AverageExample {
    public static void main(String[] args) {
        double num1 = 10;
        double num2 = 20;
        double num3 = 35;

        // Calculating the average
        double average = (num1 + num2 + num3) / 3.0;

        System.out.println("The average is: " + average);
    }
}
